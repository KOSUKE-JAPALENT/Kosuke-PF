const toggle = document.querySelector(".language-toggle");
const languageParts = toggle.querySelectorAll("span");
let currentLanguage = localStorage.getItem("portfolio-language") || "ja";

function setLanguage(language) {
  const dictionary = translations[language];

  document.documentElement.lang = language;
  document.title = dictionary.title;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (dictionary[key]) element.textContent = dictionary[key];
  });

  document.querySelectorAll("[data-i18n-html]").forEach((element) => {
    const key = element.dataset.i18nHtml;
    if (dictionary[key]) element.innerHTML = dictionary[key];
  });

  languageParts[0].classList.toggle("language-active", language === "ja");
  languageParts[2].classList.toggle("language-active", language === "en");
  toggle.setAttribute("aria-label", language === "ja" ? "Switch to English" : "日本語に切り替える");

  currentLanguage = language;
  localStorage.setItem("portfolio-language", language);
}

toggle.addEventListener("click", () => {
  setLanguage(currentLanguage === "ja" ? "en" : "ja");
});

const observer = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
        observer.unobserve(entry.target);
      }
    });
  },
  { threshold: 0.08, rootMargin: "0px 0px -40px" }
);

document.querySelectorAll(".reveal").forEach((element) => observer.observe(element));

const header = document.querySelector(".site-header");
window.addEventListener("scroll", () => {
  header.classList.toggle("is-scrolled", window.scrollY > 60);
}, { passive: true });

const sectionNavLinks = document.querySelectorAll(".section-nav a");
const sections = ["story", "work", "impact", "news", "media", "vision"].map((id) => document.getElementById(id));

const sectionObserver = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        const id = entry.target.id;
        sectionNavLinks.forEach((link) => {
          link.classList.toggle("is-active", link.getAttribute("href") === `#${id}`);
        });
      }
    });
  },
  { rootMargin: "-40% 0px -50% 0px", threshold: 0 }
);

sections.forEach((section) => {
  if (section) sectionObserver.observe(section);
});

const slideshow = document.querySelector("[data-slideshow]");
if (slideshow) {
  const slides = slideshow.querySelectorAll(".story-slideshow-track img");
  const dots = slideshow.querySelectorAll(".story-slideshow-dots span");
  let index = 0;
  let timer;

  const showSlide = (next) => {
    slides[index].classList.remove("is-active");
    dots[index].classList.remove("is-active");
    index = next;
    slides[index].classList.add("is-active");
    dots[index].classList.add("is-active");
  };

  const startSlideshow = () => {
    clearInterval(timer);
    timer = setInterval(() => {
      showSlide((index + 1) % slides.length);
    }, 4500);
  };

  dots.forEach((dot, dotIndex) => {
    dot.addEventListener("click", () => {
      showSlide(dotIndex);
      startSlideshow();
    });
  });

  startSlideshow();
}

